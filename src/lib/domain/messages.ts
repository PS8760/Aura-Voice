/**
 * Map a policy decision to a localisable reply key. Policy details stay English
 * for events/summaries; this maps the decision onto the spoken-reply catalog.
 */
export function policyReplyKey(input: {
  kind: "cancellation" | "return" | "shipping" | "cod" | "damage";
  status: string;
  rule: string;
  doorstep?: boolean;
}): string | null {
  const { kind, status, rule } = input;
  if (kind === "cancellation") {
    if (status === "denied" && rule === "cancellation.processing_only") {
      return input.doorstep ? "cancelDeniedDoorstep" : "cancelDenied";
    }
    return null;
  }
  if (kind === "return") {
    if (status === "denied" && rule === "returns.within_seven_days") return "returnDeniedLate";
    if (status === "denied" && rule === "returns.unopened_original_packaging") {
      return "returnDeniedPackaging";
    }
    return null;
  }
  if (kind === "shipping") {
    if (status === "boundary") return "shippingBoundary";
    return null;
  }
  if (kind === "cod") {
    if (status === "allowed") return "codAllowed";
    if (status === "denied") return "codDenied";
    return null;
  }
  if (kind === "damage") {
    if (status === "unknown") return "damageUnknown";
    if (status === "allowed") return "damageAllowed";
    if (status === "boundary") return "damageNeedsPhotos";
    if (status === "denied") return "damageDeniedLate";
    return null;
  }
  return null;
}
